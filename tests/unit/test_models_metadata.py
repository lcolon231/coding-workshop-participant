class TestRepresentations:
    """Every model's repr, because a repr reaches logs and tracebacks."""

    @staticmethod
    def _instances() -> dict[str, object]:
        from acme_core.models import (
            AppSecret,
            Building,
            Category,
            EngineerProfile,
            EscalationRequest,
            Floor,
            Incident,
            IncidentNote,
            IncidentStatusHistory,
            RefreshToken,
            Seat,
            User,
        )

        return {
            "User": User(
                email="a@acme.inc", full_name="A", password_hash="$2b$12$topsecrethash"
            ),
            "EngineerProfile": EngineerProfile(specialty="HVAC"),
            "RefreshToken": RefreshToken(token_hash="topsecrethash"),
            "AppSecret": AppSecret(name="jwt", value="topsecretvalue"),
            "Building": Building(code="HQ", name="Headquarters"),
            "Floor": Floor(level=3),
            "Seat": Seat(code="3A-12"),
            "Category": Category(name="HVAC"),
            "Incident": Incident(title="No heating"),
            "IncidentNote": IncidentNote(body="looking into it"),
            "IncidentStatusHistory": IncidentStatusHistory(),
            "EscalationRequest": EscalationRequest(reason="urgent"),
        }

    @pytest.mark.parametrize("name", sorted(_instances.__func__()))
    def test_repr_is_readable(self, name: str) -> None:
        text = repr(self._instances()[name])
        assert text.startswith("<") and text.endswith(">")

    @pytest.mark.parametrize("name", sorted(_instances.__func__()))
    def test_repr_leaks_no_credential(self, name: str) -> None:
        """bandit scans for exactly this, and a traceback carries it to CloudWatch."""
        assert "topsecret" not in repr(self._instances()[name])
