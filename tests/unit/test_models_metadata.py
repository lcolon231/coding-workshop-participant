class TestReferentialPolicy:
    def _ondelete(self, table: str, column: str) -> str | None:
        for fk in TABLES[table].foreign_keys:
            if fk.parent.name == column:
                return fk.ondelete
        raise AssertionError(f"no foreign key on {table}.{column}")

    def test_reporter_cannot_be_deleted_away(self) -> None:
        """RESTRICT, not CASCADE: deleting a user must not erase incident history."""
        assert self._ondelete("incidents", "reporter_id") == "RESTRICT"

    def test_assignee_is_nulled_not_cascaded(self) -> None:
        """An engineer leaving must not delete the work they were assigned."""
        assert self._ondelete("incidents", "assignee_id") == "SET NULL"

    @pytest.mark.parametrize(
        ("table", "column"),
        [
            ("incident_notes", "incident_id"),
            ("incident_status_history", "incident_id"),
            ("escalation_requests", "incident_id"),
            ("floors", "building_id"),
            ("seats", "floor_id"),
        ],
    )
    def test_children_cascade_with_their_parent(self, table: str, column: str) -> None:
        assert self._ondelete(table, column) == "CASCADE"

    def test_building_deletion_is_restricted(self) -> None:
        """Deleting a building with incidents must be a 409, not silent data loss."""
        assert self._ondelete("incidents", "building_id") == "RESTRICT"


