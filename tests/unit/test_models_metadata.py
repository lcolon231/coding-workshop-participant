"""Schema shape, asserted against the compiled DDL rather than a live database.

These run in the unit tier because they need no connection: SQLAlchemy can
compile the PostgreSQL DDL offline. Behaviour that only a real server can show
-- that a unique constraint actually rejects a duplicate -- is covered by the
integration tier.
"""

from __future__ import annotations

import pytest
from sqlalchemy import CheckConstraint, UniqueConstraint
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable

from acme_core.models import EXPECTED_TABLES, Base
from acme_core.models.enums import (
    EscalationStatus,
    IncidentStatus,
    NoteVisibility,
    Priority,
    Role,
)

pytestmark = pytest.mark.unit

TABLES = Base.metadata.tables


def ddl(table_name: str) -> str:
    """Compile a table's PostgreSQL CREATE statement."""
    return str(CreateTable(TABLES[table_name]).compile(dialect=postgresql.dialect()))


class TestMetadataCompleteness:
    def test_every_expected_table_is_registered(self) -> None:
        """A model module nothing imports is invisible to Alembic autogenerate."""
        assert set(TABLES) == set(EXPECTED_TABLES)

    def test_twelve_tables(self) -> None:
        assert len(TABLES) == 12

    @pytest.mark.parametrize("name", sorted(EXPECTED_TABLES))
    def test_every_table_compiles_for_postgresql(self, name: str) -> None:
        assert ddl(name).startswith("\nCREATE TABLE")


class TestNamingConvention:
    """Explicit constraint names keep Alembic downgrades workable.

    A constraint the database named itself cannot be reliably dropped by an
    autogenerated downgrade.
    """

    def test_primary_keys_are_named(self) -> None:
        assert TABLES["users"].primary_key.name == "pk_users"

    def test_foreign_keys_are_named(self) -> None:
        names = {fk.constraint.name for fk in TABLES["incidents"].foreign_keys}
        assert "fk_incidents_reporter_id_users" in names

    def test_unique_constraints_are_named(self) -> None:
        names = {
            c.name for c in TABLES["floors"].constraints if isinstance(c, UniqueConstraint)
        }
        assert "uq_floors_building_id_level" in names


class TestTimestamps:
    @pytest.mark.parametrize("name", sorted(EXPECTED_TABLES))
    def test_no_naive_timestamps_anywhere(self, name: str) -> None:
        """Mixing naive and aware timestamps makes SLA arithmetic silently wrong."""
        assert "WITHOUT TIME ZONE" not in ddl(name)

    def test_incidents_carry_the_four_stamps(self) -> None:
        """Denormalised so SLA reporting is a GROUP BY, not a window function."""
        columns = set(TABLES["incidents"].columns.keys())
        assert {"acknowledged_at", "assigned_at", "resolved_at", "closed_at"} <= columns

    @pytest.mark.parametrize(
        "column", ["acknowledged_at", "assigned_at", "resolved_at", "closed_at"]
    )
    def test_stamps_start_null(self, column: str) -> None:
        """A stamp must mean "this happened", so it cannot default to now()."""
        col = TABLES["incidents"].columns[column]
        assert col.nullable is True
        assert col.server_default is None


class TestEnumConstraints:
    @pytest.mark.parametrize(
        ("table", "enum_cls"),
        [
            ("users", Role),
            ("incidents", IncidentStatus),
            ("incidents", Priority),
            ("incident_notes", NoteVisibility),
            ("escalation_requests", EscalationStatus),
        ],
        ids=lambda v: getattr(v, "__name__", str(v)),
    )
    def test_every_member_appears_in_a_check(self, table: str, enum_cls: type) -> None:
        """create_constraint defaults to False; without it this is a free-text column."""
        statement = ddl(table)
        for member in enum_cls:
            assert f"'{member.value}'" in statement

    def test_checks_are_actually_emitted(self) -> None:
        checks = [
            c for c in TABLES["incidents"].constraints if isinstance(c, CheckConstraint)
        ]
        assert len(checks) >= 2

    def test_values_are_stored_not_names(self) -> None:
        """Rows must read naturally in psql: 'Facility Admin', not 'FACILITY_ADMIN'."""
        statement = ddl("users")
        assert "'Facility Admin'" in statement
        assert "FACILITY_ADMIN" not in statement


